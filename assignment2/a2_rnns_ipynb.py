# Using Conv2DTranspose decoder
def build_text2img_model_convtranspose():
    """
    Build a text-to-image model using Conv2DTranspose decoder.
    Input: X_text_onehot shape (n_samples, 5, 13) - sequence of 5 characters
    Output: y_img shape (n_samples, 3, 28, 28) - sequence of 3 images
    """
    model = tf.keras.Sequential()

    # Encoder: LSTM to process the text sequence
    model.add(LSTM(256, input_shape=(None, len(unique_characters))))

    # Repeat the encoded representation for decoder
    model.add(RepeatVector(max_answer_length))

    # Decoder: LSTM to generate output sequence
    model.add(LSTM(256, return_sequences=True))

    # Dense layer to generate feature maps
    # We'll reshape to (timesteps, 7, 7, 64) to use Conv2DTranspose
    model.add(TimeDistributed(Dense(7 * 7 * 64, activation="relu")))
    model.add(TimeDistributed(Reshape((7, 7, 64))))

    # Use Conv2DTranspose to upsample to 28x28
    # 7x7 -> 14x14 -> 28x28
    model.add(
        TimeDistributed(
            Conv2DTranspose(
                32, (3, 3), strides=(2, 2), padding="same", activation="relu"
            )
        )
    )
    model.add(
        TimeDistributed(
            Conv2DTranspose(
                1, (3, 3), strides=(2, 2), padding="same", activation="sigmoid"
            )
        )
    )

    # Remove the channel dimension: (timesteps, 28, 28, 1) -> (timesteps, 28, 28)
    model.add(TimeDistributed(Reshape((28, 28))))

    model.compile(loss="mse", optimizer="adam", metrics=["mse"])
    model.summary()

    return model


