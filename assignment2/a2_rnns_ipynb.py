# Improved Text-to-Text model with additional LSTM layers in encoder
def build_text2text_model_improved():
    """
    Build an improved text-to-text model with additional LSTM layers in the encoder.
    The first LSTM layer uses return_sequences=True to pass sequences to the next layer.
    This allows the model to capture more complex patterns in the input sequence.
    """
    model = tf.keras.Sequential()

    # First LSTM layer with return_sequences=True to pass sequences to next layer
    # This allows stacking multiple LSTM layers
    model.add(
        LSTM(256, return_sequences=True, input_shape=(None, len(unique_characters)))
    )

    # Second LSTM layer in encoder - processes the sequences from first layer
    # This can capture higher-level patterns and dependencies
    model.add(LSTM(256))  # Final encoder output

    # Repeat the encoded representation for decoder
    model.add(RepeatVector(max_answer_length))

    # Decoder: LSTM to generate output sequence
    model.add(LSTM(256, return_sequences=True))

    # Output layer: Dense layer for each time step
    model.add(TimeDistributed(Dense(len(unique_characters), activation="softmax")))

    # Compile the model
    model.compile(
        loss="categorical_crossentropy", optimizer="adam", metrics=["accuracy"]
    )
    model.summary()

    return model


