def train_and_evaluate_model(
    train_splits, model_builder, X_data, y_data, model_name=""
):
    """
    Generic function to train and evaluate models with different train/test splits.

    Args:
        train_splits: List of training set ratios (e.g., [0.5, 0.25, 0.1])
        model_builder: Function that returns a compiled model
        X_data: Input data (X_text_onehot or X_img)
        y_data: Output data (y_text_onehot)
        model_name: Optional name for the model (for display purposes)
    """
    results = {}
    for train_ratio in train_splits:
        print(
            f"Training set ratio: {train_ratio*100}%, Test set ratio: {(1-train_ratio)*100}%"
        )

        # Split data
        X_train, X_test, y_train, y_test = train_test_split(
            X_data,
            y_data,
            train_size=train_ratio,
            test_size=1 - train_ratio,
            random_state=66,
        )

        print(
            f"Training set size: {X_train.shape[0]}, Test set size: {X_test.shape[0]}"
        )

        # Build a new model for this split
        model = model_builder()

        history = model.fit(
            X_train, y_train, batch_size=32, epochs=20, validation_split=0.2
        )

        # Evaluate model
        train_loss, train_acc = model.evaluate(X_train, y_train)
        test_loss, test_acc = model.evaluate(X_test, y_test)

        # Make predictions
        y_pred = model.predict(X_test)
        y_pred_text = decode_labels(y_pred)
        y_test_text = decode_labels(y_test)

        # Calculate exact match accuracy (entire sequence must be correct)
        match_count = 0
        for i in range(len(y_test_text)):
            if y_test_text[i] == y_pred_text[i]:
                match_count += 1
        exact_match = match_count / len(y_test_text)

        print(f"Exact match accuracy: {exact_match:.4f}")

        # Plot loss
        plt.plot(history.history["loss"], label="Training loss")
        plt.plot(history.history["val_loss"], label="Validation loss")
        title = (
            f"{model_name} Model Loss (Training set ratio: {train_ratio*100}%)"
            if model_name
            else f"Model Loss (Training set ratio: {train_ratio*100}%)"
        )
        plt.title(title)
        plt.xlabel("Epoch")
        plt.ylabel("Loss")
        plt.legend()
        plt.grid(True)
        plt.show()

        # Plot accuracy
        plt.plot(history.history["accuracy"], label="Training accuracy")
        plt.plot(history.history["val_accuracy"], label="Validation accuracy")
        title = (
            f"{model_name} Model Accuracy (Training set ratio: {train_ratio*100}%)"
            if model_name
            else f"Model Accuracy (Training set ratio: {train_ratio*100}%)"
        )
        plt.title(title)
        plt.xlabel("Epoch")
        plt.ylabel("Accuracy")
        plt.legend()
        plt.grid(True)
        plt.show()

        print(f"\nTraining set ratio: {train_ratio*100}%")
        print(f"  Training accuracy: {train_acc:.4f}")
        print(f"  Test accuracy: {test_acc:.4f}")
        print(f"  Exact match accuracy: {exact_match:.4f}")

        results[train_ratio] = {
            "train_acc": train_acc,
            "test_acc": test_acc,
            "exact_match": exact_match,
        }

    return results


