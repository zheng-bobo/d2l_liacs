# Method 1: Using LSTM with flattened images
def build_img2text_model_lstm():
    """
    Build an image-to-text model using LSTM encoder with flattened images.
    Input: X_img shape (n_samples, 5, 28, 28) - sequence of 5 images
    Output: y_text_onehot shape (n_samples, 3, 13) - sequence of 3 characters
    """
    model = tf.keras.Sequential()

    # Flatten each 28x28 image to a 784-dimensional vector
    # Input shape: (5, 28, 28) -> (5, 784)
    model.add(TimeDistributed(Flatten(), input_shape=(max_query_length, 28, 28)))

    # Encoder: LSTM to process the sequence of flattened images
    model.add(LSTM(256))

    # Repeat the encoded representation for decoder
    model.add(RepeatVector(max_answer_length))

    # Decoder: LSTM to generate output sequence
    model.add(LSTM(256, return_sequences=True))

    # Output layer: Dense layer for each time step to predict character
    model.add(TimeDistributed(Dense(len(unique_characters), activation="softmax")))

    model.compile(
        loss="categorical_crossentropy", optimizer="adam", metrics=["accuracy"]
    )
    model.summary()

    return model


# Method 2: Using ConvLSTM2D
def build_img2text_model_convlstm():
    """
    Build an image-to-text model using ConvLSTM2D encoder.
    Input: X_img shape (n_samples, 5, 28, 28) - sequence of 5 images
    Output: y_text_onehot shape (n_samples, 3, 13) - sequence of 3 characters
    """
    model = tf.keras.Sequential()

    # Reshape input to add channel dimension: (5, 28, 28) -> (5, 28, 28, 1)
    model.add(
        Reshape((max_query_length, 28, 28, 1), input_shape=(max_query_length, 28, 28))
    )

    # Encoder: ConvLSTM2D to process sequence of images
    # ConvLSTM2D processes spatial-temporal data
    model.add(
        ConvLSTM2D(
            filters=32,
            kernel_size=(3, 3),
            padding="same",
            return_sequences=False,  # Only return final output
        )
    )

    # Flatten the output from ConvLSTM2D
    model.add(Flatten())

    # Dense layer to reduce dimensions before decoder
    model.add(Dense(256, activation="relu"))

    # Repeat for decoder
    model.add(RepeatVector(max_answer_length))

    # Decoder: LSTM to generate output sequence
    model.add(LSTM(256, return_sequences=True))

    # Output layer: Dense layer for each time step
    model.add(TimeDistributed(Dense(len(unique_characters), activation="softmax")))

    model.compile(
        loss="categorical_crossentropy", optimizer="adam", metrics=["accuracy"]
    )
    model.summary()

    return model


